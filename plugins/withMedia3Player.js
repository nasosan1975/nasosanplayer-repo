// ── 5. MainApplication patch ──────────────────────────────────────────────────
function withMainAppPatch(config) {
    return withDangerousMod(config, ["android", function(config) {
        var p = path.join(
            config.modRequest.platformProjectRoot,
            "app/src/main/java/com/nasosan/nasosanplayer/MainApplication.kt"
        );
        if (!fs.existsSync(p)) return config;
        var src = fs.readFileSync(p, "utf8");
        // Rimuove vecchie registrazioni (prevenzione duplicati)
        src = src.replace(/\s*add\(NasoSanPlayerPackage\(\)\)/g, "");
        src = src.replace(/\s*add\(TrackCachePackage\(\)\)/g, "");
        src = src.replace(/\s*add\(CarModePackage\(\)\)/g, "");
        src = src.replace(/\s*add\(WmaPlayerPackage\(\)\)/g, "");
        src = src.replace(/\s*add\(SpeechnotesWidgetPackage\(\)\)/g, "");
        // Aggiunge tutti i package
        if (src.includes("PackageList(this).packages.apply {")) {
            src = src.replace(
                "PackageList(this).packages.apply {",
                "PackageList(this).packages.apply {\n            add(NasoSanPlayerPackage())\n            add(TrackCachePackage())\n            add(CarModePackage())\n            add(SpeechnotesWidgetPackage())"
            );
        } else {
            src = src.replace(
                "val packages = PackageList(this).packages",
                "val packages = PackageList(this).packages\n                packages.add(NasoSanPlayerPackage())\n                packages.add(TrackCachePackage())\n                packages.add(CarModePackage())\n                packages.add(SpeechnotesWidgetPackage())"
            );
        }
        fs.writeFileSync(p, src, "utf8");
        return config;
    }]);
}

