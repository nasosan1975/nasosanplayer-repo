// ── 1. Gradle deps ────────────────────────────────────────────────────────────
function withGradleDeps(config) {
    return withAppBuildGradle(config, function(config) {
        var c = config.modResults.contents;
        // Rimuove versioni media3 esistenti (aggiornamento idempotente)
        c = c.replace(/\n\s*implementation\("androidx\.media3:[^"]*"\)/g, "");
        c = c.replace(/dependencies\s*\{/, [
            "dependencies {",
            '    implementation("androidx.media3:media3-exoplayer:' + M3V + '")',
            '    implementation("androidx.media3:media3-session:' + M3V + '")',
        ].join("\n"));
        // Rimuove vecchie dipendenze
        c = c.replace(/\n\s*implementation\("[^"]*ffmpeg-kit[^"]*"\)/g, "");
        c = c.replace(/\n\s*implementation\("androidx\.media:media:[^"]*"\)/g, "");
        if (!c.includes("libc++_shared.so")) {
            c = c.replace(/android\s*\{/,
                "android {\n    packagingOptions {\n" +
                "        pickFirst 'lib/x86/libc++_shared.so'\n" +
                "        pickFirst 'lib/x86_64/libc++_shared.so'\n" +
                "        pickFirst 'lib/armeabi-v7a/libc++_shared.so'\n" +
                "        pickFirst 'lib/arm64-v8a/libc++_shared.so'\n    }"
            );
        }
        config.modResults.contents = c;
        return config;
    });
}

// ── 2. AndroidManifest ────────────────────────────────────────────────────────
function withManifest(config) {
    return withAndroidManifest(config, function(config) {
        var manifest = config.modResults.manifest;
        if (!manifest.queries) manifest.queries = [];
        if (!manifest.queries[0]) manifest.queries[0] = {};
        if (!manifest.queries[0]["package"]) manifest.queries[0]["package"] = [];
        var hasQuery = manifest.queries[0]["package"].some(function(p) {
            return p.$ && p.$["android:name"] === "co.speechnotes.speechnotes";
        });
        if (!hasQuery) {
            manifest.queries[0]["package"].push({ $: { "android:name": "co.speechnotes.speechnotes" } });
        }
        var app = manifest.application[0];
        if (!app["meta-data"]) app["meta-data"] = [];
        var hasMeta = app["meta-data"].some(function(m) {
            return m.$ && m.$["android:name"] === "com.google.android.gms.car.application";
        });
        if (!hasMeta) {
            app["meta-data"].push({
                $: {
                    "android:name": "com.google.android.gms.car.application",
                    "android:resource": "@xml/automotive_app_desc",
                },
            });
        }
        if (!app.service) app.service = [];
        app.service = app.service.filter(function(s) {
            if (!s.$) return true;
            var n = s.$["android:name"];
            // Rimuove vecchie versioni del nostro service e MusicService di RNTP
            // (RNTP non usa setupPlayer() — il suo service crasherebbe causando backoff Android)
            return n !== "com.nasosan.nasosanplayer.NasoSanBrowserService"
                && n !== SERVICE_CLASS
                && n !== "com.doublesymmetry.trackplayer.service.MusicService";
        });
        app.service.push({
            $: {
                "android:name": SERVICE_CLASS,
                "android:foregroundServiceType": "mediaPlayback",
                "android:exported": "true",
            },
            "intent-filter": [
                {
                    action: [
                        { $: { "android:name": "androidx.media3.session.MediaLibraryService" } },
                    ],
                },
                {
                    action: [
                        { $: { "android:name": "android.media.browse.MediaBrowserService" } },
                    ],
                },
            ],
        });
        return config;
    });
}

// ── 3. automotive_app_desc.xml ────────────────────────────────────────────────
function withAutomotiveXml(config) {
    return withDangerousMod(config, ["android", function(config) {
        var xmlDir = path.join(config.modRequest.platformProjectRoot, "app/src/main/res/xml");
        fs.mkdirSync(xmlDir, { recursive: true });
        fs.writeFileSync(
            path.join(xmlDir, "automotive_app_desc.xml"),
            '<?xml version="1.0" encoding="utf-8"?>\n<automotiveApp>\n    <uses name="media"/>\n</automotiveApp>\n',
            "utf8"
        );
        return config;
    }]);
}

